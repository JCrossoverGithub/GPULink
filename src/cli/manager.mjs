import { spawn } from 'node:child_process';
import { lstatSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { defaultLocalSetupDirectory } from './setup-directory.mjs';
import { defaultServerSetupDirectory, hasServerMarker, readServerSetup } from './server-profile.mjs';
import { hasRemoteWorkerMarker } from './remote-worker-profile.mjs';
import { readLocalSmokeSetup } from './local-smoke.mjs';
import { inspectManagedLocal } from './local-lifecycle.mjs';
import { createManager, loadProfile } from '../../manager/gateway.mjs';
import { readSnapshot } from '../../manager/snapshot.mjs';

const usage = 'Usage: gpulink [--config-dir DIRECTORY] manager [--enable-controls] [--no-open]';
function present(file) {
  try { lstatSync(file); return true; }
  catch (error) { if (error.code === 'ENOENT') return false; throw error; }
}
export function selectManagerDirectory(explicit, local=defaultLocalSetupDirectory(), server=defaultServerSetupDirectory()) {
  if (explicit) return path.resolve(explicit);
  const choices=[local,server].filter(present);
  if (choices.length !== 1) throw new Error(choices.length ? 'Both default installations exist. Select one with --config-dir.' : 'No default installation. Initialize a local or server profile, or select an existing one with --config-dir.');
  return choices[0];
}
export function managerOptions(args) {
  if (args.length===1 && args[0]==='--help') return {help:true};
  if (new Set(args).size!==args.length || args.some(a=>!['--enable-controls','--no-open'].includes(a))) throw new Error(usage);
  return {controls:args.includes('--enable-controls'),open:!args.includes('--no-open')};
}
export function browserCommand(env=process.env, release='') {
  // No shell, operator-provided command, or user data in arguments. The URL
  // is generated by the loopback listener. SSH/headless users get a URL only.
  if (env.SSH_CONNECTION || env.SSH_TTY) return null;
  if (/microsoft/i.test(release)) return 'explorer.exe';
  return env.DISPLAY || env.WAYLAND_DISPLAY ? 'xdg-open' : null;
}
function openBrowser(url,output) {
  let release='';try{release=readFileSync('/proc/sys/kernel/osrelease','utf8');}catch{}
  const command=browserCommand(process.env,release);
  if (!command) {output.log('Open the printed URL in your browser.');return;}
  try {
    const child=spawn(command,[url],{stdio:'ignore',detached:true,windowsHide:true});
    child.once('error',()=>output.log('Browser launch unavailable. Open the printed URL manually.'));
    child.unref();
  } catch {output.log('Browser launch unavailable. Open the printed URL manually.');}
}
export async function runManager(args, explicit, {output=console}={}) {
  let options;
  try {options=managerOptions(args);} catch {output.error(usage);return 2;}
  if(options.help){output.log(usage);return 0;}
  if(process.platform!=='linux'){output.error('Manager requires a Linux or WSL installation-owned control plane. Native Windows managed services are not supported.');return 1;}
  let directory, config;
  try {
    directory=selectManagerDirectory(explicit);
    if(['GPULINK_URL','GPULINK_ADMIN_TOKEN','GPULINK_CLIENT_TOKEN'].some(k=>Object.hasOwn(process.env,k)))throw new Error('Inherited GPULINK role configuration conflicts with Manager. Clear GPULINK_URL, GPULINK_ADMIN_TOKEN and GPULINK_CLIENT_TOKEN first.');
    if(hasRemoteWorkerMarker(directory))throw new Error('Remote worker profile selected. Launch Manager on the control-plane host.');
    // Validate private role files before reading the full generated profile.
    const roleConfig=loadProfile(directory);
    const server=hasServerMarker(directory);
    const setup=server?readServerSetup(directory):readLocalSmokeSetup(directory);
    if(setup.profiles['admin.env'].GPULINK_ADMIN_TOKEN!==roleConfig.adminToken||setup.profiles['client.env'].GPULINK_CLIENT_TOKEN!==roleConfig.clientToken)throw new Error('Installation credentials changed during inspection.');
    const assertCore=async()=>{if(await inspectManagedLocal(setup)!=='ready')throw new Error('Selected installation ownership is not ready.');};
    await assertCore();
    config={...roleConfig,controls:options.controls,installation:{kind:server?'server':'local',name:path.basename(directory)},assertCore};
    // Authenticate only after verifying the selected installation owner. Reject
    // unsupported older Core snapshots before exposing an HTTP listener.
    await readSnapshot(config);
  } catch(error) {
    // Profile parsers and upstream errors are not echoed (may contain private data).
    const allowed=['Both default installations exist.','No default installation.','Remote worker profile selected.','Inherited GPULINK role configuration conflicts with Manager.'];
    output.error(allowed.some(p=>error.message?.startsWith(p))?error.message:'Manager startup refused: select a private, running GPULink local/server installation with a compatible Core. Check gpulink local status or server status.');
    return 1;
  }
  const listener=createManager(config);
  let stopping=false;
  const stop=()=>{if(stopping)return;stopping=true;listener.closeEventStreams();listener.close();listener.closeAllConnections();};
  process.once('SIGINT',stop);process.once('SIGTERM',stop);
  try {
    return await new Promise(resolve=>{
      listener.once('error',()=>{output.error('Manager could not listen. No other service was stopped.');resolve(1);stop();});
      listener.once('close',()=>resolve(0));
      listener.listen(0,'127.0.0.1',()=>{
        const url=`http://127.0.0.1:${listener.address().port}/`;
        output.log(url);
        output.log(`GPULink Manager | ${config.installation.kind} installation: ${directory}`);
        output.log(options.controls?'OPERATOR MODE: trusted local operator only.':'READ ONLY');
        output.log('Ctrl+C closes Manager only; Core and workers remain running.');
        if(options.open)openBrowser(url,output);
      });
    });
  } finally {process.removeListener('SIGINT',stop);process.removeListener('SIGTERM',stop);}
}
